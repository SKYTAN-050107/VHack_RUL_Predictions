import streamlit as st
import requests
import pandas as pd

# API Base URL
API_URL = "http://localhost:8000/api"

st.set_page_config(page_title="Input ML Data - VHACK", page_icon="📊", layout="wide")

# Check authentication
if "authenticated" not in st.session_state or not st.session_state.authenticated:
    st.title("Access Denied")
    st.warning("Please log in on the [Home Page](../app.py) to access this tool.")
    st.stop()

st.title("Input Machinery ML Data")
st.markdown("""
Upload sensor data in CSV format to predict the Remaining Useful Life (RUL) for your machinery. 
The system expects vibration, temperature, and load data.
Files such as sample_sensor_data.csv are input/demo files, not generated by the ML model.
""")

# Helper to call API
def get_machines():
    try:
        response = requests.get(f"{API_URL}/machines/")
        if response.status_code == 200:
            return response.json()
    except:
        pass
    return []


def get_model_catalog():
    fallback_ids = ["FD001", "FD002", "FD003", "FD004"]
    fallback_readiness = {
        dataset_id: {
            "available": False,
            "message": "Model availability unknown",
        }
        for dataset_id in fallback_ids
    }
    try:
        response = requests.get(f"{API_URL}/machines/models/options", timeout=10)
        if response.status_code == 200:
            payload = response.json()
            options = payload.get("dataset_ids", [])
            if options:
                return {
                    "dataset_ids": options,
                    "readiness": payload.get("readiness", fallback_readiness),
                    "ready_dataset_ids": payload.get("ready_dataset_ids", []),
                }
    except Exception:
        pass
    return {
        "dataset_ids": fallback_ids,
        "readiness": fallback_readiness,
        "ready_dataset_ids": [],
    }

# Select machine
machines = get_machines()
if not machines:
    st.error("No machines found in the database. Please initialize the database with some machines.")
else:
    machine_names = [f"{m['id']} - {m['name']}" for m in machines]
    selected_name = st.selectbox("Select Machine for Sensor Data Upload", machine_names)
    machine_id = selected_name.split(" - ")[0]
    model_catalog = get_model_catalog()
    dataset_options = model_catalog.get("dataset_ids", ["FD001", "FD002", "FD003", "FD004"])
    selected_dataset = st.selectbox("Select Model Dataset", dataset_options, index=0)
    readiness = model_catalog.get("readiness", {})
    selected_readiness = readiness.get(selected_dataset, {})
    selected_available = bool(selected_readiness.get("available", False))

    if selected_available:
        st.success(f"{selected_dataset} model is ready for inference.")
    else:
        st.warning(
            f"{selected_dataset} model is not ready: "
            f"{selected_readiness.get('message', 'Model artifact not found')}"
        )
        st.caption("Upload preview still works, but prediction run is disabled until a model is available.")

    # CSV Upload
    st.subheader("Sensor Data Upload")
    csv_file = st.file_uploader("Drag and drop CSV here", type=["csv"], key="csv_uploader")

    if csv_file:
        df = pd.read_csv(csv_file)
        st.write("Preview of uploaded sensor data:")
        st.dataframe(df.head())
        
        if st.button("Predict RUL and Update Machine Status", disabled=not selected_available):
            with st.spinner("Analyzing sensor data with ML model..."):
                files = {"file": (csv_file.name, csv_file.getvalue(), "text/csv")}
                resp = requests.post(
                    f"{API_URL}/machines/{machine_id}/upload-sensor-data",
                    files=files,
                    params={"dataset_id": selected_dataset},
                    timeout=30,
                )
                
                if resp.status_code == 200:
                    data = resp.json()["prediction"]
                    st.success(f"Success! Machine {data['machine_id']} updated.")
                    st.write(f"**Predicted RUL:** {data['predicted_rul']} cycles")
                    st.write(f"**New Status:** {data['status']}")
                    st.write(f"**Dataset Used:** {data.get('dataset_id', selected_dataset)}")
                    st.write(f"**Health State:** {data.get('health_state', 'Unknown')}")

                    if data.get("change_point_detected"):
                        cp_step = data.get("change_point_step")
                        if cp_step is not None:
                            st.warning(f"Change point detected at cycle index {cp_step}.")
                        else:
                            st.warning("Change point detected in recent readings.")

                    explanation = data.get("explanation")
                    if explanation:
                        st.info(explanation)
                else:
                    st.error(f"Failed to process sensor data: {resp.text}")

st.info("Uploaded CSV data is used as model input. The model predicts RUL from the data; it does not generate the CSV.")
